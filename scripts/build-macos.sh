#!/usr/bin/env bash
# build-macos.sh — builds Valve's Wine (external/wine, `macos` branch) for macOS.
#
# Unix side: x86_64 (runs under Rosetta 2), winemac.drv, new WoW64 (no 32-bit unix libs).
# PE side:   i386 + x86_64 built with llvm-mingw.
#
# The macOS 27 Command Line Tools are arm64-only, so this is a cross build from the arm64 host:
#   1. prepare  — copy the source and run Wine's generators + autoreconf (submodule stays clean)
#   2. tools    — native arm64 build of Wine's build tools (winebuild, widl, wrc, ...)
#   3. wine     — cross build for x86_64-apple-darwin using those tools, then install
#                 (--disable-loader64: Valve-only loader copy for the Linux i386-unix layout;
#                  not needed on macOS and its preloader lacks preloader_mac.o)
#
# Usage: scripts/build-macos.sh [prepare|tools|wine|rebuild|all]   (default: all)
#        rebuild = sync changed sources into the build tree and re-run make (no reconfigure)
# Env:   BUILD_DIR    (default <repo>/build)
#        DIST_DIR     (default <repo>/dist/wine)
#        DEPS_X86_64  (default ~/.local/opt/proton-macos-deps/x86_64, from build-deps.sh)
#        LLVM_MINGW   (default ~/.local/opt/llvm-mingw)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BUILD_DIR="${BUILD_DIR:-$ROOT/build}"
DIST_DIR="${DIST_DIR:-$ROOT/dist/wine}"
DEPS="${DEPS_X86_64:-$HOME/.local/opt/proton-macos-deps/x86_64}"
LLVM_MINGW="${LLVM_MINGW:-$HOME/.local/opt/llvm-mingw}"
JOBS="$(sysctl -n hw.ncpu)"

SRC="$BUILD_DIR/wine-src"
TOOLS="$BUILD_DIR/wine-tools"
OBJ="$BUILD_DIR/wine-x86_64"

# llvm-mingw goes last: its `clang` must not shadow Apple clang for the unix side.
export PATH="/opt/homebrew/opt/bison/bin:/opt/homebrew/opt/flex/bin:$PATH:$LLVM_MINGW/bin"
export MACOSX_DEPLOYMENT_TARGET=11.0

log() { printf '\033[1m==> %s\033[0m\n' "$*" >&2; }

prepare() {
  log "Preparing source in $SRC"
  mkdir -p "$SRC"
  rsync -a --delete --exclude .git "$ROOT/external/wine/" "$SRC/"
  (
    cd "$SRC"
    # Same generator steps as Proton's Makefile.in (.wine-post-source) plus autoreconf.
    XDG_CACHE_HOME="$BUILD_DIR/cache" dlls/winevulkan/make_vulkan -x vk.xml -X video.xml
    tools/make_requests
    tools/make_specfiles
    autoreconf -fi
  )
}

tools() {
  log "Building native (arm64) Wine tools in $TOOLS"
  mkdir -p "$TOOLS"
  (
    cd "$TOOLS"
    # FreeType (arm64, Homebrew) is needed by sfnt2fon to build the bitmap fonts.
    "$SRC/configure" --without-x --disable-tests \
      --without-gstreamer --without-vulkan --without-opencl --without-sdl --without-gnutls
    make -j"$JOBS" __tooldeps__
    # wrc/wmc look for NLS tables next to the tools tree (<tools>/nls) in out-of-tree builds.
    mkdir -p nls
    cp "$SRC"/nls/*.nls nls/
  )
}

wine() {
  log "Cross-building Wine for x86_64-apple-darwin in $OBJ"
  mkdir -p "$OBJ"
  (
    cd "$OBJ"
    PKG_CONFIG=/opt/homebrew/bin/pkg-config \
    PKG_CONFIG_PATH="$DEPS/lib/pkgconfig" PKG_CONFIG_LIBDIR="$DEPS/lib/pkgconfig" \
    LDFLAGS="-L$DEPS/lib" \
    CC="/usr/bin/clang -arch x86_64" CXX="/usr/bin/clang++ -arch x86_64" OBJC="/usr/bin/clang -arch x86_64" \
    "$SRC/configure" \
      --build=aarch64-apple-darwin --host=x86_64-apple-darwin \
      --with-wine-tools="$TOOLS" \
      --enable-archs=i386,x86_64 \
      --disable-loader64 \
      --prefix="$DIST_DIR" \
      --disable-tests --without-x --without-wayland \
      --with-freetype --with-vulkan \
      --without-gstreamer --without-opencl --without-sdl --without-gnutls
    make -j"$JOBS"
    make install
  )
  link_loader
  log "Installed to $DIST_DIR"
}

# Wine 11 installs the loader in lib/wine/x86_64-unix; the cross build does not create bin/wine.
# Wine dlopen()s its unix deps by leaf name (e.g. "libfreetype.6.dylib"), so we ship them in
# $DIST_DIR/lib and the launcher puts that directory on DYLD_FALLBACK_LIBRARY_PATH.
link_loader() {
  ln -sf ../lib/wine/x86_64-unix/wine "$DIST_DIR/bin/wine"
  cp -a "$DEPS"/lib/*.dylib "$DIST_DIR/lib/"
  # DXVK (macOS fork) in Proton's layout: lib/wine/dxvk/<arch>-windows
  if [[ -d "$DEPS/dxvk" ]]; then
    mkdir -p "$DIST_DIR/lib/wine/dxvk/x86_64-windows" "$DIST_DIR/lib/wine/dxvk/i386-windows"
    cp -a "$DEPS"/dxvk/x64/*.dll "$DIST_DIR/lib/wine/dxvk/x86_64-windows/"
    cp -a "$DEPS"/dxvk/x32/*.dll "$DIST_DIR/lib/wine/dxvk/i386-windows/"
  fi
}

rebuild() {
  log "Incremental rebuild in $OBJ"
  # --update: keep files regenerated by prepare (make_requests, make_specfiles) that are newer.
  rsync -a --update --exclude .git "$ROOT/external/wine/" "$SRC/"
  make -C "$OBJ" -j"$JOBS"
  make -C "$OBJ" install
  link_loader
}

step="${1:-all}"
case "$step" in
  prepare) prepare ;;
  tools)   tools ;;
  wine)    wine ;;
  rebuild) rebuild ;;
  all)     prepare; tools; wine ;;
  *) echo "usage: $0 [prepare|tools|wine|rebuild|all]" >&2; exit 2 ;;
esac
